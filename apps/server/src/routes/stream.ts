import {
  encodeSseEvent,
  pathTo,
  SendMessageBodySchema,
  SSE_HEARTBEAT,
  type StreamEvent,
  type ToolResult,
} from '@keyring/shared';
import { Hono } from 'hono';
import { streamSSE } from 'hono/streaming';
import type { AppDeps } from '../app';
import { DEFAULT_TITLE, type StoredMessage } from '../db/repository';
import { apiError, clientKey, parseJson } from '../lib/http';
import { isAbortError, sleep } from '../lib/util';
import { titleFor, detectIntent } from '../providers/mockScripts';
import { ProviderError } from '../providers/types';

/** Simulated failures trigger after this many text deltas (or at the end of short replies). */
const FAIL_AFTER_DELTAS = 25;

export function streamRoutes({ repo, registry, debug, limiter }: AppDeps) {
  const app = new Hono();
  /** Assistant message ids currently being generated by this process. */
  const active = new Set<string>();

  app.post('/conversations/:id/messages', async (c) => {
    const conversationId = c.req.param('id');
    const conversation = repo.getConversation(conversationId);
    if (!conversation) return apiError(c, 404, 'not_found', 'Conversation not found');

    const body = await parseJson(c, SendMessageBodySchema);
    if (!body.ok) return apiError(c, 400, 'bad_request', body.message);
    const req = body.data;

    const debugMode = debug.consume(c.req.header('x-keyring-debug'));
    if (debugMode === 'server_error') {
      return apiError(c, 500, 'internal', 'Simulated server error (debug mode).');
    }
    const wait = debugMode === 'rate_limit' ? 8_000 : limiter.take(clientKey(c));
    if (wait > 0) {
      return apiError(c, 429, 'rate_limited', 'You’re sending messages too quickly. Please wait a moment.', wait);
    }

    const { provider, model } = registry.resolve(req.model);
    const all = repo.listMessages(conversationId);
    const byId = new Map(all.map((m) => [m.id, m] as const));

    let userMessage: StoredMessage | null = null;
    let assistant: StoredMessage;
    let historyLeafId: string;

    switch (req.intent) {
      case 'send': {
        if (req.parentId !== null) {
          const parent = byId.get(req.parentId);
          if (!parent) return apiError(c, 400, 'bad_request', 'parentId is not in this conversation');
          if (parent.status === 'streaming') {
            return apiError(c, 409, 'conflict', 'A reply is still being generated for this message');
          }
        }
        if (!repo.attachmentsExist(req.attachmentIds)) {
          return apiError(c, 400, 'bad_request', 'One or more attachments do not exist');
        }
        userMessage = repo.createMessage({
          conversationId,
          parentId: req.parentId,
          role: 'user',
          content: req.content,
          status: 'complete',
          attachmentIds: req.attachmentIds,
        });
        historyLeafId = userMessage.id;
        assistant = repo.createMessage({
          conversationId,
          parentId: userMessage.id,
          role: 'assistant',
          content: '',
          status: 'streaming',
          model,
        });
        break;
      }
      case 'regenerate': {
        const user = byId.get(req.userMessageId);
        if (!user || user.role !== 'user') return apiError(c, 400, 'bad_request', 'userMessageId is not a user message');
        historyLeafId = user.id;
        assistant = repo.createMessage({
          conversationId,
          parentId: user.id,
          role: 'assistant',
          content: '',
          status: 'streaming',
          model,
        });
        break;
      }
      case 'resume': {
        const existing = byId.get(req.assistantMessageId);
        if (!existing || existing.role !== 'assistant' || !existing.parentId) {
          return apiError(c, 400, 'bad_request', 'assistantMessageId is not an assistant reply');
        }
        const orphaned = existing.status === 'streaming' && !active.has(existing.id);
        if (existing.status !== 'error' && existing.status !== 'stopped' && !orphaned) {
          return apiError(c, 409, 'conflict', 'Only stopped or failed replies can be resumed');
        }
        historyLeafId = existing.parentId;
        assistant = repo.updateMessage(existing.id, { status: 'streaming', error: null, model })!;
        break;
      }
    }

    const history = pathTo(repo.listMessages(conversationId), historyLeafId);
    const controller = new AbortController();
    c.req.raw.signal.addEventListener('abort', () => controller.abort(), { once: true });
    c.header('X-Accel-Buffering', 'no'); // disable proxy buffering (nginx, Render, Fly)

    active.add(assistant.id);
    return streamSSE(c, async (stream) => {
      stream.onAbort(() => controller.abort());
      const send = (event: StreamEvent) => stream.write(encodeSseEvent(event));
      const heartbeat = setInterval(() => {
        void stream.write(SSE_HEARTBEAT).catch(() => undefined);
      }, 15_000);

      let content = assistant.content;
      const toolResults: ToolResult[] = [...assistant.toolResults];
      let trace: unknown = null;
      let deltas = 0;
      let lastPersist = Date.now();
      const persistPartial = () => {
        repo.updateMessage(assistant.id, { content, toolResults });
        lastPersist = Date.now();
      };

      /** Bumps updatedAt and replaces the default title (on completion, stop or error). */
      const touchAndTitle = () => {
        const convo = repo.updateConversation(conversationId, { touch: true })!;
        if (convo.title !== DEFAULT_TITLE) return convo;
        const text = history.find((m) => m.role === 'user')?.content ?? '';
        return repo.updateConversation(conversationId, { title: titleFor(detectIntent(text), text) })!;
      };

      const injectFailure = async (): Promise<'dropped' | void> => {
        if (debugMode === 'fail_mid_stream') {
          repo.updateMessage(assistant.id, {
            content,
            toolResults,
            status: 'error',
            error: { code: 'network', message: 'Connection lost mid-reply (simulated).' },
          });
          controller.abort();
          return 'dropped'; // close without message_end: the client sees a dropped connection
        }
        if (debugMode === 'provider_error') {
          throw new ProviderError('provider_error', 'The model provider failed mid-reply (simulated).', true);
        }
      };

      try {
        await send({
          type: 'message_start',
          userMessage: userMessage ? repo.toPublic(userMessage) : null,
          assistantMessage: repo.toPublic(assistant),
        });

        const events = provider.stream({
          history,
          assistantMessageId: assistant.id,
          prefix: assistant.content,
          existingToolResults: assistant.toolResults,
          model,
          mode: req.mode,
          signal: controller.signal,
          loadAttachment: (id) => repo.getAttachmentData(id),
        });

        for await (const event of events) {
          if (event.type === 'trace') {
            trace = event.trace;
            continue;
          }
          if (debugMode === 'slow') await sleep(120 + Math.random() * 180, controller.signal);
          if (event.type === 'text') {
            content += event.delta;
            deltas++;
            await send({ type: 'text_delta', messageId: assistant.id, delta: event.delta });
          } else {
            const placed = { ...event.result, offset: content.length };
            toolResults.push(placed);
            await send({ type: 'tool_result', messageId: assistant.id, result: placed });
            persistPartial();
          }
          if (Date.now() - lastPersist > 400) persistPartial();
          if (deltas === FAIL_AFTER_DELTAS && (await injectFailure()) === 'dropped') return;
        }
        if (deltas < FAIL_AFTER_DELTAS && (await injectFailure()) === 'dropped') return;

        const final = repo.updateMessage(assistant.id, {
          content,
          toolResults,
          status: 'complete',
          error: null,
          providerTrace: trace,
        })!;
        const convo = touchAndTitle();
        await send({ type: 'message_end', message: repo.toPublic(final), conversation: convo });
      } catch (err) {
        if (controller.signal.aborted || isAbortError(err)) {
          // User pressed Stop (or the connection dropped): keep the partial reply.
          const current = repo.getMessage(assistant.id);
          if (current?.status === 'streaming') {
            repo.updateMessage(assistant.id, { content, toolResults, status: 'stopped' });
          }
          touchAndTitle();
          return;
        }
        const failure =
          err instanceof ProviderError
            ? err
            : new ProviderError('internal', 'Something went wrong while generating the reply.', true);
        if (!(err instanceof ProviderError)) console.error('[stream] unexpected error', err);
        repo.updateMessage(assistant.id, {
          content,
          toolResults,
          status: 'error',
          error: { code: failure.code, message: failure.message },
        });
        touchAndTitle();
        await send({
          type: 'error',
          messageId: assistant.id,
          code: failure.code,
          message: failure.message,
          retryable: failure.retryable,
          ...(failure.retryAfterMs !== undefined ? { retryAfterMs: failure.retryAfterMs } : {}),
        }).catch(() => undefined);
      } finally {
        clearInterval(heartbeat);
        active.delete(assistant.id);
      }
    });
  });

  return app;
}
